"""AI backends for chai.

Hosted and served chat models all go through one backend, ``llm.LLMComponent``, built on LiteLLM;
the provider is part of the model id (``gemini/...``, ``vertex_ai/...``, ``ollama_chat/...``,
``lm_studio/...``, ``hosted_vllm/...``, ``openai/...``, ``anthropic/...``). The named backends
(``GeminiComponent``, ``OllamaComponent``, ``LMStudioComponent``, ``OpenAIComponent``,
``VLLMComponent``, ``SGLangComponent``) are thin subclasses that keep each provider's defaults and
the component names existing workflows use. ``TransformersComponent`` and ``MLXVLMComponent`` run
models in-process instead. System One decision models live in ``chai.system_one`` and are used by
the ``chai.decision`` roles rather than mixed into the text roles.

Two exported lists drive how role-mixin classes (``GeminiTranscriber``, ``LLMClassifier``,
``VLLMSegmenter`` ...) are auto-generated:

* ``__all__`` -- components that get composite classes auto-generated by
  :func:`create_all_components` (consumed by ``chai.transcriber``, ``chai.classifier``, etc.).
* ``__more_than_all__`` -- components that are exported and importable but intentionally skipped by
  the auto-generator (e.g. ``TransformersComponent``, which loads heavy local weights and is wired
  up via explicit subclasses).

Optional backends whose dependencies are platform-specific are registered defensively so importing
``chai.ai`` keeps working when a backend's deps aren't installed -- ``mlx-vlm`` only exists on Apple
Silicon.
"""

import logging

logger = logging.getLogger("chai")

from .gemini import GeminiComponent
from .llm import LLMComponent
from .lm_studio import LMStudioComponent
from .ollama import OllamaComponent
from .openai import OpenAIComponent
from .sglang import SGLangComponent
from .transformers import TransformersComponent
from .vllm import VLLMComponent

__all__ = [
    LLMComponent,
    GeminiComponent,
    LMStudioComponent,
    OllamaComponent,
    OpenAIComponent,
    VLLMComponent,
    SGLangComponent,
]

__more_than_all__ = [TransformersComponent]

